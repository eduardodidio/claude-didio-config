#!/usr/bin/env python3
"""Code-generation module for poc-from-minutes pipeline.

Exposes two functions consumed by the pipeline orchestrator (T05):
  mock_gen(manifest, dest, log_fn)  — writes src/mocks/<Entity>.ts
  ui_gen(manifest, dest, log_fn)    — writes src/pages/<Slug>.tsx + App.tsx
"""
from __future__ import annotations

import re
from pathlib import Path

HEADER = "// auto-generated by didio poc-from-minutes — DO NOT EDIT BY HAND\n"

TS_TYPE: dict[str, str] = {
    "id":      "string",
    "string":  "string",
    "number":  "number",
    "boolean": "boolean",
    "date":    "string",
}


def example_value(field: dict, idx: int, entity_name: str) -> str:
    """Return the JS literal for a sample value, idx-indexed (1-based)."""
    t = field["type"]
    n = field["name"]
    if t == "id":
        return f'"e{idx}"'
    if t == "string":
        return f'"{entity_name} {idx}"' if n.lower() in ("name", "title", "label") \
            else f'"{n}-{idx}"'
    if t == "number":
        return str(idx * 10)
    if t == "boolean":
        return "true" if idx % 2 == 1 else "false"
    if t == "date":
        return f'"2026-{idx:02d}-01"'
    return '"?"'


def mock_gen(manifest: dict, dest: Path, log_fn) -> None:
    out_dir = dest / "src" / "mocks"
    out_dir.mkdir(parents=True, exist_ok=True)
    n_per = (manifest.get("mocks") or {}).get("records_per_entity", 5)
    if not 3 <= n_per <= 10:
        n_per = 5
    if (manifest.get("mocks") or {}).get("use_msw"):
        log_fn(dest, "mock_gen", True,
               "use_msw=true noted but MVP ignores; static mocks only")
    for ent in sorted(manifest["entities"], key=lambda e: e["name"]):
        name = ent["name"]
        plural = name.lower() + ("s" if not name.lower().endswith("s") else "")
        interface_lines = [f"export interface {name} {{"]
        for f in ent["fields"]:
            interface_lines.append(f"  {f['name']}: {TS_TYPE[f['type']]};")
        interface_lines.append("}")
        data_lines = [f"export const {plural}: {name}[] = ["]
        for i in range(1, n_per + 1):
            fields = ", ".join(
                f"{f['name']}: {example_value(f, i, name)}"
                for f in ent["fields"]
            )
            data_lines.append(f"  {{ {fields} }},")
        data_lines.append("];")
        body = HEADER + "\n".join(interface_lines) + "\n\n" \
               + "\n".join(data_lines) + "\n"
        (out_dir / f"{name}.ts").write_text(body)
    log_fn(dest, "mock_gen", True,
           f"wrote {len(manifest['entities'])} mock files, "
           f"{n_per} records each")


def slug_for_path(path: str) -> str:
    """'/users/list' -> 'UsersList'; '/' -> 'Home'."""
    if path == "/" or path == "":
        return "Home"
    parts = re.split(r"[/:]+", path.strip("/"))
    return "".join(p.capitalize() for p in parts if p) or "Page"


def ui_gen(manifest: dict, dest: Path, log_fn) -> None:
    pages_dir = dest / "src" / "pages"
    pages_dir.mkdir(parents=True, exist_ok=True)

    seen_slugs: dict[str, int] = {}
    screen_records = []  # [(path, title, slug, data_shape)]
    for s in manifest["screens"]:
        slug = slug_for_path(s["path"])
        if slug in seen_slugs:
            seen_slugs[slug] += 1
            slug = f"{slug}_{seen_slugs[slug]}"
        else:
            seen_slugs[slug] = 1
        screen_records.append(
            (s["path"], s["title"], slug, s.get("data_shape"))
        )

    entity_by_name = {e["name"]: e for e in manifest["entities"]}

    for path, title, slug, ds in screen_records:
        if ds and ds in entity_by_name:
            ent = entity_by_name[ds]
            plural = ds.lower() + ("s" if not ds.lower().endswith("s") else "")
            field_headers = "".join(
                f'<th className="text-left p-2">{f["name"]}</th>'
                for f in ent["fields"]
            )
            field_cells = "".join(
                f'<td className="p-2">{{String(item.{f["name"]})}}</td>'
                for f in ent["fields"]
            )
            body = f'''{HEADER}import {{ {plural} }} from "@/mocks/{ds}";

export default function {slug}() {{
  return (
    <div className="p-6">
      <h1 className="text-2xl font-bold mb-4">{title}</h1>
      <table className="w-full border-collapse">
        <thead><tr>{field_headers}</tr></thead>
        <tbody>
          {{{plural}.map((item, idx) => (
            <tr key={{idx}}>{field_cells}</tr>
          ))}}
        </tbody>
      </table>
    </div>
  );
}}
'''
        else:
            body = f'''{HEADER}export default function {slug}() {{
  return (
    <div className="p-6">
      <h1 className="text-2xl font-bold mb-4">{title}</h1>
      <p className="text-sm text-muted-foreground">POC placeholder.</p>
    </div>
  );
}}
'''
        (pages_dir / f"{slug}.tsx").write_text(body)

    # rewrite App.tsx
    imports = "\n".join(
        f'import {slug} from "@/pages/{slug}";'
        for _, _, slug, _ in screen_records
    )
    nav_links = "\n      ".join(
        f'<Link to="{p}">{t}</Link>'
        for p, t, _, _ in screen_records
    )
    routes = "\n        ".join(
        f'<Route path="{p}" element={{<{slug} />}} />'
        for p, _, slug, _ in screen_records
    )
    first_path = screen_records[0][0]
    redirect = "" if first_path == "/" else \
        f'\n        <Route path="/" element={{<Navigate to="{first_path}" replace />}} />'
    app_tsx = f'''{HEADER}import {{ BrowserRouter, Routes, Route, Link, Navigate }} from "react-router-dom";
{imports}

export default function App() {{
  return (
    <BrowserRouter>
      <nav className="p-4 border-b flex gap-4">
      {nav_links}
      </nav>
      <Routes>
        {routes}{redirect}
        <Route path="*" element={{<div className="p-6">404</div>}} />
      </Routes>
    </BrowserRouter>
  );
}}
'''
    (dest / "src" / "App.tsx").write_text(app_tsx)
    # remove the .tmpl variant if scaffold left one (defensive)
    tmpl = dest / "src" / "App.tsx.tmpl"
    if tmpl.exists():
        tmpl.unlink()
    log_fn(dest, "ui_gen", True,
           f"wrote {len(screen_records)} pages + App.tsx with "
           f"{len(screen_records)} routes")
